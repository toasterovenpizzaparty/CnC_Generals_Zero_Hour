#!/usr/bin/env python3
"""Generate CMake source lists from the original Visual C++ 6 project files (.dsp).

The .dsp files remain the authoritative list of what EA compiled.  This script extracts the
source files of the Release configuration (honouring per-file "Exclude_From_Build") and writes
one cmake/sources/<name>.cmake per project, defining <NAME>_SOURCES relative to the Code dir.

Run from GeneralsMD/Code:  python3 cmake/dsp_to_cmake.py
"""
import os
import re

PROJECTS = {
    # cmake list name : .dsp path (relative to GeneralsMD/Code)
    "WWDEBUG": "Libraries/Source/WWVegas/WWDebug/wwdebug.dsp",
    "WWLIB": "Libraries/Source/WWVegas/WWLib/wwlib.dsp",
    "WWMATH": "Libraries/Source/WWVegas/WWMath/wwmath.dsp",
    "WWSAVELOAD": "Libraries/Source/WWVegas/WWSaveLoad/wwsaveload.dsp",
    "WWUTIL": "Libraries/Source/WWVegas/Wwutil/wwutil.dsp",
    "WW3D2": "Libraries/Source/WWVegas/WW3D2/ww3d2.dsp",
    "WWSHADE": "Libraries/Source/WWVegas/wwshade/wwshade.dsp",
    "COMPRESSION": "Libraries/Source/Compression/Compression.dsp",
    "GAMEENGINE": "GameEngine/GameEngine.dsp",
    "GAMEENGINEDEVICE": "GameEngineDevice/GameEngineDevice.dsp",
    "RTS": "RTS.dsp",
}

CFG_RE = re.compile(r'!(?:ELSE)?IF\s+"\$\(CFG\)" == "([^"]+)"(.*?)(?=!ELSEIF|!ENDIF)', re.S)


def is_release(cfg_name):
    n = cfg_name.lower()
    return "release" in n and "debug" not in n


def sources(dsp_path):
    text = open(dsp_path, encoding="latin-1").read()
    base = os.path.dirname(dsp_path)
    result = []
    for block in re.findall(r"# Begin Source File(.*?)# End Source File", text, re.S):
        m = re.search(r"SOURCE=(.*)", block)
        if not m:
            continue
        src = m.group(1).strip().strip('"').replace("\\", "/")
        if not re.search(r"\.(cpp|c|cxx)$", src, re.I):
            continue
        excluded = False
        cfgs = CFG_RE.findall(block)
        if cfgs:
            for name, body in cfgs:
                if is_release(name) and "Exclude_From_Build 1" in body:
                    excluded = True
        elif "Exclude_From_Build 1" in block:
            excluded = True
        path = os.path.normpath(os.path.join(base, src)).replace("\\", "/")
        if excluded:
            continue
        # case-insensitive fix-up (the .dsp files were written on Windows)
        if not os.path.exists(path):
            d, f = os.path.split(path)
            if os.path.isdir(d):
                for cand in os.listdir(d):
                    if cand.lower() == f.lower():
                        path = os.path.join(d, cand)
                        break
        result.append(path)
    return result


def main():
    os.makedirs("cmake/sources", exist_ok=True)
    for name, dsp in PROJECTS.items():
        srcs = sources(dsp)
        present = [s for s in srcs if os.path.exists(s)]
        missing = [s for s in srcs if not os.path.exists(s)]
        with open(f"cmake/sources/{name.lower()}.cmake", "w") as out:
            out.write(f"# Generated by cmake/dsp_to_cmake.py from {dsp} - do not edit.\n")
            out.write(f"set({name}_SOURCES\n")
            for s in present:
                out.write(f"    \"{s}\"\n")
            out.write(")\n")
            if missing:
                out.write("# Listed in the .dsp but not part of the source release:\n")
                for s in missing:
                    out.write(f"#   {s}\n")
        print(f"{name:18s} {len(present):4d} files ({len(missing)} missing)")


if __name__ == "__main__":
    main()
